#!/usr/bin/env python3
"""Generate only board-specific wiring; upstream RTL is read, never rewritten."""
from pathlib import Path
import sys,re,argparse
ROOT=Path(__file__).resolve().parents[3]
sys.path.insert(0,str(ROOT))
from opentpu import target
ap=argparse.ArgumentParser(description=__doc__)
ap.add_argument('--target',type=Path,default=ROOT/'targets/f2.toml')
ap.add_argument('--output',type=Path,default=ROOT/'build/f2/cl_opentpu.sv')
ap.add_argument('--hdk',type=Path,required=True,help='Full AWS FPGA HDK root')
args=ap.parse_args()
T=target.load(str(args.target.resolve()))
board=(ROOT/'rtl/shell/otpu_board.sv').read_text()
allowed=set(re.findall(r'parameter\s+(?:int|bit|logic\s*\[[^]]+\])\s+(\w+)',board))
p={k:v for k,v in target.rtl_params(T).items() if k in allowed}
p.update(HAS_I2C=0,HOSTCAL=0,CORE_KHZ=T.core_khz,BUILD_ID=0x7e42a626)
s=['// Generated by scripts/generate_f2_top.py. Platform/HBM wiring only.\nmodule cl_opentpu (\n`include "cl_ports.vh"\n);']
used=set()
def line(t):s.append(t)
def inst(mod,name,con,params=None):
    for v in con.values(): used.update(re.findall(r'\b\w+\b',v))
    h=mod
    if params: h+=' #(\n  '+',\n  '.join('.'+k+'('+str(v)+')' for k,v in params.items())+'\n)'
    line(h+' '+name+' (\n  '+',\n  '.join('.'+k+'('+v+')' for k,v in con.items())+'\n);')
def decl(name,width=1,suffix=''):
    line('logic '+(f'[{width-1}:0] ' if width>1 else '')+name+suffix+';')
line('logic core_clk, tmem_clk, hbm_clk, core_locked, hbm_locked;\nlogic core_rst_n, hbm_rst_n, rst_main_n_sync, core_rst;\nlogic [2:0] leds; logic hbm_ready, hbm_ready_core;')
inst('f2_core_clk','u_core_clk',dict(clk_in1='clk_main_a0',reset='!rst_main_n',locked='core_locked',clk_out1='core_clk',clk_out2='tmem_clk'))
inst('f2_hbm_clk','u_hbm_clk',dict(clk_in1='clk_hbm_ref',reset='!rst_main_n',locked='hbm_locked',clk_out1='hbm_clk'))
for name,clk,src,out in [('main','clk_main_a0','rst_main_n','rst_main_n_sync'),('core','core_clk','rst_main_n && core_locked && hbm_locked','core_rst_n'),('hbm','hbm_clk','rst_main_n && hbm_locked','hbm_rst_n')]:
    inst('xpm_cdc_async_rst','u_rst_'+name,dict(src_arst=src,dest_clk=clk,dest_arst=out),dict(DEST_SYNC_FF=4,RST_ACTIVE_HIGH=0))
line('always_ff @(posedge core_clk) core_rst <= !core_rst_n;')
inst('xpm_cdc_single','u_ready_cdc',dict(src_clk='clk_main_a0',src_in='hbm_ready',dest_clk='core_clk',dest_out='hbm_ready_core'),dict(DEST_SYNC_FF=4,SRC_INPUT_REG=0))
# AXI Lite clock crossing.
axil={'awaddr':32,'awvalid':1,'awready':1,'wdata':32,'wstrb':4,'wvalid':1,'wready':1,'bresp':2,'bvalid':1,'bready':1,'araddr':32,'arvalid':1,'arready':1,'rdata':32,'rresp':2,'rvalid':1,'rready':1}
for k,w in axil.items():decl('ctl_'+k,w)
responses={'awready','wready','bresp','bvalid','arready','rdata','rresp','rvalid'}
c=dict(s_axi_aclk='clk_main_a0',s_axi_aresetn='rst_main_n_sync',m_axi_aclk='core_clk',m_axi_aresetn='core_rst_n')
for k in axil:
    c['s_axi_'+k]=('cl_ocl_' if k in responses else 'ocl_cl_')+k
    c['m_axi_'+k]='ctl_'+k
c.update(s_axi_awprot="3'd0",s_axi_arprot="3'd0",m_axi_awprot='',m_axi_arprot='')
inst('f2_ocl_cdc','u_ocl_cdc',c)
# Accelerator native channels.
native={'cvalid':1,'cready':1,'cwe':1,'caddr':25,'wvalid':1,'wready':1,'wdata':512,'wmask':64,'rvalid':1,'rdata':512,'wdone':16,'err':1}
for k,w in native.items():line('logic [1:0]'+(f'[{w-1}:0]' if w>1 else '')+' n_'+k+';')
c=dict(clk='core_clk',clk_f='tmem_clk',rst='core_rst',ctl_mrst='core_rst',calib='{2{hbm_ready_core}}',ded="2'b0",temp="12'd0",led='leds',i2c_lo='',i2c_pin="5'b11111")
for k in axil:c['s_ctl_'+k]='ctl_'+k+('[11:0]' if k in ('araddr','awaddr') else '')
for k in native:c['n_'+k]='n_'+k
inst('otpu_board','u_board',c,p)
axi={'awaddr':34,'awvalid':1,'awready':1,'wdata':512,'wstrb':64,'wvalid':1,'wready':1,'bvalid':1,'bresp':2,'bready':1,'araddr':34,'arlen':8,'arvalid':1,'arready':1,'rdata':512,'rvalid':1,'rlast':1,'rresp':2,'rready':1}
for ch in range(2):
    for k,w in axi.items():decl(f'n{ch}_'+k,w)
    c=dict(clk='core_clk',rst='core_rst')
    for k in native:c['n_'+k]=f'n_{k}[{ch}]'
    for k in axi:c['m_'+k]=f'n{ch}_'+k
    inst('otpu_native_axi','u_native'+str(ch),c,dict(BASE_ADDR=f"34'h{ch*0x80000000:x}"))
# External HBM arrays: use AXI ports 0/4, tie unused 1..3 low.
hbm={'araddr':34,'arburst':2,'arid':6,'arlen':4,'arsize':3,'arvalid':1,'awaddr':34,'awburst':2,'awid':6,'awlen':4,'awsize':3,'awvalid':1,'rready':1,'bready':1,'wdata':256,'wlast':1,'wstrb':32,'wvalid':1,'arready':1,'awready':1,'rdata':256,'rid':6,'rlast':1,'rresp':2,'rvalid':1,'wready':1,'bid':6,'bresp':2,'bvalid':1}
hbm_out={'arready','awready','rdata','rid','rlast','rresp','rvalid','wready','bid','bresp','bvalid'}
for k,w in hbm.items():decl('h_'+k,w,' [0:4]')
# HBM accepts only aligned 32-byte transfers. SmartConnect packs bursts but
# preserves a narrow single beat. WSTRB preserves writes; full reads are safe
# because this boundary addresses ordinary HBM memory, never MMIO registers.
for k in ('awaddr','araddr'):decl('hb_'+k,34,' [0:4]')
for j in range(5):
    inst('otpu_hbm_geometry','u_geometry'+str(j),dict(s_awaddr=f'h_awaddr[{j}]',s_araddr=f'h_araddr[{j}]',m_awaddr=f'hb_awaddr[{j}]',m_araddr=f'hb_araddr[{j}]'))
for j in (1,2,3):
    for k in sorted(hbm.keys()-hbm_out):line(f"assign h_{k}[{j}] = '0;")
line("cfg_bus_t hbm_stat();\nassign hbm_stat.wr=1'b0;\nassign hbm_stat.rd=1'b0;\nassign hbm_stat.addr='0;\nassign hbm_stat.wdata='0;")
c=dict(apb_clk='clk_hbm_ref',i_clk_250m='clk_main_a0',i_rst_250m_n='rst_main_n_sync',i_clk_450m='hbm_clk',i_rst_450m_n='hbm_rst_n',hbm_stat_bus='hbm_stat',o_cl_sh_hbm_stat_int='',o_hbm_ready='hbm_ready')
for k in hbm:c[('o' if k in hbm_out else 'i')+'_axi_'+k]=('hb_' if k in ('awaddr','araddr') else 'h_')+k
for j in range(2):
    for k in ('preset_n','paddr','pprot','psel','penable','pwrite','pwdata','pstrb','pready','prdata','pslverr'):
        c[('i' if k=='preset_n' else 'o')+f'_hbm_apb_{k}_{j}']=f'hbm_apb_{k}_{j}'
inst('cl_mem_hbm_wrapper','u_hbm',c,dict(NUM_OF_AXI_PORTS=5,AXI4_INTERFACE=0))
# SmartConnect: retains full PCIS ID/address and rejects unmapped requests.
c=dict(core_clk='core_clk',host_clk='clk_main_a0',hbm_clk='hbm_clk',aresetn='core_rst_n')
allaxi=list(hbm)+['awcache','awlock','awprot','awqos','arcache','arlock','arprot','arqos']
host_width = dict(hbm, awaddr=64, araddr=64, awid=16, arid=16, bid=16, rid=16, awlen=8, arlen=8, wdata=512, rdata=512, wstrb=64, awcache=4, awlock=1, awprot=3, awqos=4, arcache=4, arlock=1, arprot=3, arqos=4)
pipe = dict(aclk='clk_main_a0',aresetn='rst_main_n_sync',s_axi_awregion="4'd0",s_axi_arregion="4'd0",m_axi_awregion='',m_axi_arregion='')
for k in allaxi:
    decl('pcis_'+k,host_width[k])
    pipe['s_axi_'+k]=('cl_sh_dma_pcis_' if k in hbm_out else 'sh_cl_dma_pcis_')+k
    pipe['m_axi_'+k]='pcis_'+k
    c['S_HOST_'+k]='pcis_'+k
inst('f2_pcis_pipe','u_pcis_pipe',pipe)
for ch in range(2):
    for k in allaxi:
        if k in axi:v=f'n{ch}_'+k
        elif k in ('arid','awid'):v="1'b0"
        elif k in ('rid','bid'):v=''
        elif k in ('arlen','awlen'):v="8'd0"
        elif k in ('arburst','awburst'):v="2'b01"
        elif k in ('arsize','awsize'):v="3'd6"
        elif k=='wlast':v="1'b1"
        elif k in ('awcache','arcache'):v="4'b0000" # device non-bufferable: B means visibility
        else:v="'0"
        c[f'S_N{ch}_'+k]=v
for port in (0,4):
    # SmartConnect's generated downstream ports omit IDs (one ordered thread).
    for k in allaxi:
        if k not in ('arid','awid','rid','bid'):
            c[f'M_H{port}_'+k]=f'h_{k}[{port}]' if k in hbm else ''
    line(f"assign h_arid[{port}] = 6'd0;")
    line(f"assign h_awid[{port}] = 6'd0;")
inst('f2_mem_wrapper','u_mem',c)
# Required disabled DDR stub plus safe shell unused-interface implementations.
iface=args.hdk/'common/shell_stable/design/interfaces'
for inc in ('unused_ddr_template.inc','unused_cl_sda_template.inc','unused_flr_template.inc','unused_apppf_irq_template.inc'):
    line('`include "'+inc+'"')
    used.update(re.findall(r'\b\w+\b',(iface/inc).read_text()))
ports=(iface/'cl_ports.vh').read_text()
outputs=re.findall(r'output\s+logic\s*(?:\[[^]]+\]\s*)?(\w+)',ports)
# Independent diagnostic bits cross from core to the shell's 250 MHz domain.
# Register the combinational LED values at their source before synchronization.
decl('shell_status',5)
inst('xpm_cdc_array_single','u_status_cdc',
     dict(src_clk='core_clk',src_in='{n_err,leds}',dest_clk='clk_main_a0',dest_out='shell_status'),
     dict(WIDTH=5,DEST_SYNC_FF=4,SRC_INPUT_REG=1,INIT_SYNC_FF=1,SIM_ASSERT_CHK=0))
constants={'cl_sh_id0':"32'hf0011d0f",'cl_sh_id1':"32'h1d51fedd",'cl_sh_status0':"32'h4f545055",'cl_sh_status1':"32'h7e42a626",'cl_sh_status2':"{30'd0,shell_status[4:3]}",'cl_sh_status_vled':"{12'd0,hbm_ready,shell_status[2:0]}"}
for name in outputs:
    if name not in used: line('assign '+name+' = '+constants.get(name,"'0")+';')
line('endmodule')
args.output.parent.mkdir(parents=True,exist_ok=True)
args.output.write_text('\n'.join(s)+'\n')
print('Generated cl_opentpu with architecture hash',hex(p['ARCH_HASH']))
