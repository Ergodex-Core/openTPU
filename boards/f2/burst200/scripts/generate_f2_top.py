#!/usr/bin/env python3
"""Generate only board-specific wiring; upstream RTL is read, never rewritten.

The target's S slices (targets/f2-burst200.toml: one; targets/f2-burst200-s3.toml: three,
docs/v4/f2-burst200-s3.md) on Alex's burst200 fabric: per slice two otpu_native_axi adapters
and one f2_mem SmartConnect block design (3 SI x 2 MI) onto two HBM AXI ports (the platform's
hbm_ports: window j = 2 s + c of slice s's channel c at HBM address j x 2 GiB on port
hbm_ports[j]); one cl_mem_hbm_wrapper covering the highest port used. With one slice the output
is the checked-in rtl/boards/f2/burst200/cl_opentpu.sv byte for byte (tests/test_f2_burst200_s3.py).
With more, one slice per SLR (slice s in SLR s; four slices: the target's slice_slr, slices 2 and
3 both in SLR2, targets/f2-burst200-s4.toml; the control block, the collective hub and the
OCL converter in SLR1 with the shell's OCL; every SmartConnect and the HBM wrapper in SLR0 at the
HBM's ports): slice s's native AXI reaches its SmartConnect through one axi_register_slice per
SLR hop (f2_native_pipe), the PCIS enters in SLR1 (f2_pcis_pipe), fans out through a
SmartConnect crossbar there (f2_host, one master port per slice's 4 GiB) and reaches each
slice's SmartConnect in SLR0 through a register slice (f2_pcis_pipe again); a reset
synchronizer and a 4-stage pipe per SLR and clock (the HDK's cl_dram_hbm_dma pattern)."""
from pathlib import Path
import sys,re,argparse
ROOT=Path(__file__).resolve().parents[4]
sys.path.insert(0,str(ROOT))
from opentpu import target
# otpu_board parameters added after Alex's base (7e42a626): left out at their defaults, which his
# checked-in wrapper relies on (the one-slice output stays byte-identical)
LATE_DEFAULTS={'NCH':2,'CH_LOG2':31,'DRAM_LOG2':32}


def geometry(T):
    """(S, NCH, the HBM AXI port of each window j = 2 s + c, the wrapper's port count)."""
    S,NCH=T.arch['S'],T.platform['channels_per_slice']
    if NCH!=2 or T.platform['channel_bytes']!=1<<31:
        raise SystemExit('the burst200 fabric takes two 2 GiB channels per slice')
    ports=list(T.platform.get('hbm_ports',[0,4]))
    if len(ports)!=NCH*S or len(set(ports))!=len(ports) or not all(0<=p<32 for p in ports):
        raise SystemExit(f'hbm_ports: {NCH*S} distinct HBM AXI ports 0..31')
    if len({p//2 for p in ports})!=len(ports):
        raise SystemExit('hbm_ports: ports 2k and 2k+1 share one HBM channel; pick distinct channels')
    return S,NCH,ports,max(ports)+1


def slice_slrs(T):
    """The SLR of each slice of a multi-slice top: the target's [platform] slice_slr, else slice
    s in SLR s (S <= 3). Slice s's native masters take one register slice per SLR hop down to
    SLR0 (its SLR's number of them) and the reset of its SLR. Four slices put two in one SLR
    (targets/f2-burst200-s4.toml: [0, 1, 2, 2], docs/v4/p4-status.md)."""
    S=T.arch['S']
    slrs=list(T.platform.get('slice_slr',range(S)))
    if len(slrs)!=S or not all(r in (0,1,2) for r in slrs):
        raise SystemExit(f'slice_slr: an SLR 0..2 for each of the {S} slices')
    return slrs


def host_xbar_slr(T):
    """The SLR of the host crossbar of a multi-slice top: the target's [platform] host_xbar_slr.
    1 (the default, S = 3's): beside the shell's PCIS in SLR1, then a register slice per slice
    down to SLR0, so S 512-bit host channels cross SLR1 -> SLR0. 0: in SLR0 beside the
    SmartConnects behind one register slice at the crossing's SLR0 end (u_pcis_hop), so one
    channel crosses: the four-slice placement had ~14.4K of the ~17.3K SLLs the CL can use at the
    SLR0 / SLR1 boundary (columns X0-X5) taken, ~5.1K of them the host's four channels."""
    v=T.platform.get('host_xbar_slr',1)
    if v not in (0,1):
        raise SystemExit('host_xbar_slr: 0 or 1')
    return v


def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--target',type=Path,default=ROOT/'targets/f2-burst200.toml')
    ap.add_argument('--output',type=Path,default=ROOT/'build/f2/cl_opentpu.sv')
    ap.add_argument('--hdk',type=Path,required=True,help='Full AWS FPGA HDK root')
    args=ap.parse_args()
    T=target.load(str(args.target.resolve()))
    text=generate(T,args.hdk)
    args.output.parent.mkdir(parents=True,exist_ok=True)
    args.output.write_text(text)
    print('Generated cl_opentpu with architecture hash',hex(target.rtl_params(T)['ARCH_HASH']))


def generate(T,hdk:Path)->str:
    S,NCH,ports,NPORTS=geometry(T)
    multi=S>1
    slrs=slice_slrs(T)                         # slice s's SLR (multi)
    NW=NCH*S                                   # windows (channels) in all
    board=(ROOT/'rtl/shell/otpu_board.sv').read_text()
    allowed=set(re.findall(r'parameter\s+(?:int|bit|logic\s*\[[^]]+\])\s+(\w+)',board))
    p={k:v for k,v in target.rtl_params(T).items() if k in allowed and LATE_DEFAULTS.get(k,None)!=v}
    p.update(HAS_I2C=0,HOSTCAL=0,CORE_KHZ=T.core_khz,BUILD_ID=0x7e42a626)
    s=['// Generated by scripts/generate_f2_top.py. Platform/HBM wiring only.\nmodule cl_opentpu (\n`include "cl_ports.vh"\n);']
    used=set()
    def line(t):s.append(t)
    def lit(v):
        """A parameter value: an unsized decimal, except from 2^31 up a sized 32-bit one
        (Vivado reads an unsized decimal as a signed 32-bit integer and truncates: an
        ARCH_HASH above 2^31 would be wrong in silicon)."""
        return f"32'd{v}" if isinstance(v,int) and not isinstance(v,bool) and v>=1<<31 else str(v)
    def inst(mod,name,con,params=None):
        for v in con.values(): used.update(re.findall(r'\b\w+\b',v))
        h=mod
        if params: h+=' #(\n  '+',\n  '.join('.'+k+'('+lit(v)+')' for k,v in params.items())+'\n)'
        line(h+' '+name+' (\n  '+',\n  '.join('.'+k+'('+v+')' for k,v in con.items())+'\n);')
    def decl(name,width=1,suffix=''):
        line('logic '+(f'[{width-1}:0] ' if width>1 else '')+name+suffix+';')
    line('logic core_clk, tmem_clk, hbm_clk, core_locked, hbm_locked;\nlogic core_rst_n, hbm_rst_n, rst_main_n_sync, core_rst;\nlogic [2:0] leds; logic hbm_ready, hbm_ready_core;')
    inst('f2_core_clk','u_core_clk',dict(clk_in1='clk_main_a0',reset='!rst_main_n',locked='core_locked',clk_out1='core_clk',clk_out2='tmem_clk'))
    inst('f2_hbm_clk','u_hbm_clk',dict(clk_in1='clk_hbm_ref',reset='!rst_main_n',locked='hbm_locked',clk_out1='hbm_clk'))
    for name,clk,src,out in [('main','clk_main_a0','rst_main_n','rst_main_n_sync'),('core','core_clk','rst_main_n && core_locked && hbm_locked','core_rst_n'),('hbm','hbm_clk','rst_main_n && hbm_locked','hbm_rst_n')]:
        inst('xpm_cdc_async_rst','u_rst_'+name,dict(src_arst=src,dest_clk=clk,dest_arst=out),dict(DEST_SYNC_FF=4,RST_ACTIVE_HIGH=0))
    line('always_ff @(posedge core_clk) core_rst <= !core_rst_n;')
    # the SLR of each piece (multi): slice s in SLR slrs[s] (slice_slrs: s, or the target's
    # slice_slr); core_rst_n above is SLR1's (the control block's, with the OCL); SLR0 and SLR2
    # get their own synchronizer and a 4-stage pipe in each clock they use (the HDK's
    # cl_dram_hbm_dma: CDC_ASYNC_RST_N_SLR*, SLR*_PIPE_RST_N), never one reset net across SLRs
    def core_rst_n(slr):return 'core_rst_n' if slr==1 else f'core_rst_n_slr{slr}'
    def core_rst(slr):return 'core_rst' if slr==1 else f'core_rst_slr{slr}'
    def main_rst_n(slr):return 'rst_main_n_sync' if slr==1 else f'rst_main_n_slr{slr}'
    if multi:
        line('// per-SLR resets: a synchronizer and a 4-stage pipe in each SLR (no reset net across SLRs)')
        for slr in sorted(set(slrs)|{0}):     # SLR0 always: the SmartConnects' core side
            if slr==1:continue
            decl(f'core_rst_n_slr{slr}_s');decl(f'core_rst_n_slr{slr}');decl(f'core_rst_slr{slr}')
            inst('xpm_cdc_async_rst',f'u_rst_core_slr{slr}',dict(src_arst='rst_main_n && core_locked && hbm_locked',dest_clk='core_clk',dest_arst=f'core_rst_n_slr{slr}_s'),dict(DEST_SYNC_FF=4,RST_ACTIVE_HIGH=0))
            inst('lib_pipe',f'u_rstpipe_core_slr{slr}',dict(clk='core_clk',rst_n="1'b1",in_bus=f'core_rst_n_slr{slr}_s',out_bus=f'core_rst_n_slr{slr}'),dict(WIDTH=1,STAGES=4))
            line(f'always_ff @(posedge core_clk) core_rst_slr{slr} <= !core_rst_n_slr{slr};')
        # the host clock in SLR0 (the slices' SmartConnects' host side and its register slices)
        decl('rst_main_n_slr0_s');decl('rst_main_n_slr0')
        inst('xpm_cdc_async_rst','u_rst_main_slr0',dict(src_arst='rst_main_n',dest_clk='clk_main_a0',dest_arst='rst_main_n_slr0_s'),dict(DEST_SYNC_FF=4,RST_ACTIVE_HIGH=0))
        inst('lib_pipe','u_rstpipe_main_slr0',dict(clk='clk_main_a0',rst_n="1'b1",in_bus='rst_main_n_slr0_s',out_bus='rst_main_n_slr0'),dict(WIDTH=1,STAGES=4))
    inst('xpm_cdc_single','u_ready_cdc',dict(src_clk='clk_main_a0',src_in='hbm_ready',dest_clk='core_clk',dest_out='hbm_ready_core'),dict(DEST_SYNC_FF=4,SRC_INPUT_REG=0))
    # AXI Lite clock crossing.
    axil={'awaddr':32,'awvalid':1,'awready':1,'wdata':32,'wstrb':4,'wvalid':1,'wready':1,'bresp':2,'bvalid':1,'bready':1,'araddr':32,'arvalid':1,'arready':1,'rdata':32,'rresp':2,'rvalid':1,'rready':1}
    for k,w in axil.items():decl('ctl_'+k,w)
    responses={'awready','wready','bresp','bvalid','arready','rdata','rresp','rvalid'}
    c=dict(s_axi_aclk='clk_main_a0',s_axi_aresetn='rst_main_n_sync',m_axi_aclk='core_clk',m_axi_aresetn='core_rst_n')
    for k in axil:
        c['s_axi_'+k]=('cl_ocl_' if k in responses else 'ocl_cl_')+k
        c['m_axi_'+k]='ctl_'+k
    c.update(s_axi_awprot="3'd0",s_axi_arprot="3'd0",m_axi_awprot='',m_axi_arprot='')
    inst('f2_ocl_cdc','u_ocl_cdc',c)
    # Accelerator native channels.
    native={'cvalid':1,'cready':1,'cwe':1,'caddr':25,'wvalid':1,'wready':1,'wdata':512,'wmask':64,'rvalid':1,'rdata':512,'wdone':16,'err':1}
    for k,w in native.items():line(f'logic [{NW-1}:0]'+(f'[{w-1}:0]' if w>1 else '')+' n_'+k+';')
    c=dict(clk='core_clk',clk_f='tmem_clk',rst='core_rst',ctl_mrst='core_rst',calib=f'{{{NW}{{hbm_ready_core}}}}',ded=f"{NW}'b0",temp="12'd0",led='leds',i2c_lo='',i2c_pin="5'b11111")
    for k in axil:c['s_ctl_'+k]='ctl_'+k+('[11:0]' if k in ('araddr','awaddr') else '')
    for k in native:c['n_'+k]='n_'+k
    inst('otpu_board','u_board',c,p)
    axi={'awaddr':34,'awvalid':1,'awready':1,'wdata':512,'wstrb':64,'wvalid':1,'wready':1,'bvalid':1,'bresp':2,'bready':1,'araddr':34,'arlen':8,'arvalid':1,'arready':1,'rdata':512,'rvalid':1,'rlast':1,'rresp':2,'rready':1}
    for ch in range(NW):
        for k,w in axi.items():decl(f'n{ch}_'+k,w)
        c=dict(clk='core_clk',rst=core_rst(slrs[ch//NCH] if multi else 1))
        for k in native:c['n_'+k]=f'n_{k}[{ch}]'
        for k in axi:c['m_'+k]=f'n{ch}_'+k
        inst('otpu_native_axi','u_native'+str(ch),c,dict(BASE_ADDR=f"34'h{ch*0x80000000:x}"))
    # External HBM arrays: the ports used, the others tied low.
    hbm={'araddr':34,'arburst':2,'arid':6,'arlen':4,'arsize':3,'arvalid':1,'awaddr':34,'awburst':2,'awid':6,'awlen':4,'awsize':3,'awvalid':1,'rready':1,'bready':1,'wdata':256,'wlast':1,'wstrb':32,'wvalid':1,'arready':1,'awready':1,'rdata':256,'rid':6,'rlast':1,'rresp':2,'rvalid':1,'wready':1,'bid':6,'bresp':2,'bvalid':1}
    hbm_out={'arready','awready','rdata','rid','rlast','rresp','rvalid','wready','bid','bresp','bvalid'}
    for k,w in hbm.items():decl('h_'+k,w,f' [0:{NPORTS-1}]')
    # HBM accepts only aligned 32-byte transfers. SmartConnect packs bursts but
    # preserves a narrow single beat. WSTRB preserves writes; full reads are safe
    # because this boundary addresses ordinary HBM memory, never MMIO registers.
    for k in ('awaddr','araddr'):decl('hb_'+k,34,f' [0:{NPORTS-1}]')
    for j in range(NPORTS):
        inst('otpu_hbm_geometry','u_geometry'+str(j),dict(s_awaddr=f'h_awaddr[{j}]',s_araddr=f'h_araddr[{j}]',m_awaddr=f'hb_awaddr[{j}]',m_araddr=f'hb_araddr[{j}]'))
    for j in range(NPORTS):
        if j in ports:continue
        for k in sorted(hbm.keys()-hbm_out):line(f"assign h_{k}[{j}] = '0;")
    line("cfg_bus_t hbm_stat();\nassign hbm_stat.wr=1'b0;\nassign hbm_stat.rd=1'b0;\nassign hbm_stat.addr='0;\nassign hbm_stat.wdata='0;")
    c=dict(apb_clk='clk_hbm_ref',i_clk_250m='clk_main_a0',i_rst_250m_n='rst_main_n_sync',i_clk_450m='hbm_clk',i_rst_450m_n='hbm_rst_n',hbm_stat_bus='hbm_stat',o_cl_sh_hbm_stat_int='',o_hbm_ready='hbm_ready')
    for k in hbm:c[('o' if k in hbm_out else 'i')+'_axi_'+k]=('hb_' if k in ('awaddr','araddr') else 'h_')+k
    for j in range(2):
        for k in ('preset_n','paddr','pprot','psel','penable','pwrite','pwdata','pstrb','pready','prdata','pslverr'):
            c[('i' if k=='preset_n' else 'o')+f'_hbm_apb_{k}_{j}']=f'hbm_apb_{k}_{j}'
    inst('cl_mem_hbm_wrapper','u_hbm',c,dict(NUM_OF_AXI_PORTS=NPORTS,AXI4_INTERFACE=0))
    # SmartConnect: retains full PCIS ID/address and rejects unmapped requests.
    allaxi=list(hbm)+['awcache','awlock','awprot','awqos','arcache','arlock','arprot','arqos']
    host_width = dict(hbm, awaddr=64, araddr=64, awid=16, arid=16, bid=16, rid=16, awlen=8, arlen=8, wdata=512, rdata=512, wstrb=64, awcache=4, awlock=1, awprot=3, awqos=4, arcache=4, arlock=1, arprot=3, arqos=4)
    pipe = dict(aclk='clk_main_a0',aresetn='rst_main_n_sync',s_axi_awregion="4'd0",s_axi_arregion="4'd0",m_axi_awregion='',m_axi_arregion='')
    for k in allaxi:
        decl('pcis_'+k,host_width[k])
        pipe['s_axi_'+k]=('cl_sh_dma_pcis_' if k in hbm_out else 'sh_cl_dma_pcis_')+k
        pipe['m_axi_'+k]='pcis_'+k
    inst('f2_pcis_pipe','u_pcis_pipe',pipe)
    def native_master(ch):
        """The SmartConnect's S_N port connections for window ch's adapter master."""
        out={}
        for k in allaxi:
            if k in axi:v=f'n{ch}_'+k
            elif k in ('arid','awid'):v="1'b0"
            elif k in ('rid','bid'):v=''
            elif k in ('arlen','awlen'):v="8'd0"
            elif k in ('arburst','awburst'):v="2'b01"
            elif k in ('arsize','awsize'):v="3'd6"
            elif k=='wlast':v="1'b1"
            elif k in ('awcache','arcache'):v="4'b0000" # device non-bufferable: B means visibility
            else:v="'0"
            out[k]=v
        return out
    native_width=dict(hbm,awid=1,arid=1,bid=1,rid=1,awlen=8,arlen=8,wdata=512,rdata=512,wstrb=64,awcache=4,awlock=1,awprot=3,awqos=4,arcache=4,arlock=1,arprot=3,arqos=4)
    def register_slice(ip,name,clk,rstn,src,width,dst):
        """An axi_register_slice `ip` named `name` from the connections `src` (signal per AXI
        key; a constant or '' on the slave side) to new nets `dst`_<k>."""
        con=dict(aclk=clk,aresetn=rstn,s_axi_awregion="4'd0",s_axi_arregion="4'd0",m_axi_awregion='',m_axi_arregion='')
        out={}
        for k in allaxi:
            decl(f'{dst}_'+k,width[k])
            con['s_axi_'+k]=src[k]
            con['m_axi_'+k]=f'{dst}_'+k
            out[k]=f'{dst}_'+k
        inst(ip,name,con)
        return out
    if not multi:
        c=dict(core_clk='core_clk',host_clk='clk_main_a0',hbm_clk='hbm_clk',aresetn='core_rst_n')
        for k in allaxi:c['S_HOST_'+k]='pcis_'+k
        for ch in range(2):
            for k,v in native_master(ch).items():c[f'S_N{ch}_'+k]=v
        for port in ports:
            # SmartConnect's generated downstream ports omit IDs (one ordered thread).
            for k in allaxi:
                if k not in ('arid','awid','rid','bid'):
                    c[f'M_H{port}_'+k]=f'h_{k}[{port}]' if k in hbm else ''
            line(f"assign h_arid[{port}] = 6'd0;")
            line(f"assign h_awid[{port}] = 6'd0;")
        inst('f2_mem_wrapper','u_mem',c)
    else:
        # the host's fan-out: the PCIS pipe (SLR1) into the f2_host crossbar (master port s =
        # slice s's 4 GiB at HBM address 4 s GiB), then one register slice per slice in SLR0
        # (every slice's SmartConnect is there), f2_pcis_pipe again. The crossbar in SLR1
        # (host_xbar_slr 1), or in SLR0 behind one more f2_pcis_pipe at the crossing (0)
        xin={k:'pcis_'+k for k in allaxi}
        xrst='rst_main_n_sync'
        if host_xbar_slr(T)==0:
            xin=register_slice('f2_pcis_pipe','u_pcis_hop','clk_main_a0',main_rst_n(0),xin,host_width,'ph')
            xrst=main_rst_n(0)
        c=dict(host_clk='clk_main_a0',aresetn=xrst)
        for k in allaxi:c['S_PCIS_'+k]=xin[k]
        ids=('arid','awid','rid','bid')
        for sl in range(S):
            # SmartConnect's generated downstream ports omit IDs (one ordered thread), as the
            # memory block designs' M_H*: the slice's host side takes ID 0 (S_HOST keeps its
            # 16-bit IDs, Alex's f2_mem as it is), its response IDs go nowhere
            for k in allaxi:
                if k in ids:continue
                decl(f'hx{sl}_'+k,host_width[k])
                c[f'M_S{sl}_'+k]=f'hx{sl}_'+k
        inst('f2_host_wrapper','u_host',c)
        for sl in range(S):
            src={k:("16'd0" if k in ('arid','awid') else '' if k in ('rid','bid') else f'hx{sl}_'+k) for k in allaxi}
            host=register_slice('f2_pcis_pipe',f'u_host_pipe{sl}','clk_main_a0',main_rst_n(0),src,host_width,f'hp{sl}')
            # slice s's native masters down to SLR0: a register slice per hop (f2_native_pipe,
            # placed in the hop's destination SLR: u_npipe<ch>_slr<k>)
            masters=[]
            for ch in range(NCH*sl,NCH*sl+NCH):
                m=native_master(ch)
                for hop in range(slrs[sl]-1,-1,-1):
                    m=register_slice('f2_native_pipe',f'u_npipe{ch}_slr{hop}','core_clk',core_rst_n(hop),m,native_width,f'np{ch}_slr{hop}')
                masters.append(m)
            c=dict(core_clk='core_clk',host_clk='clk_main_a0',hbm_clk='hbm_clk',aresetn=core_rst_n(0))
            for k in allaxi:c['S_HOST_'+k]=host[k]
            for ch in range(NCH):
                for k,v in masters[ch].items():c[f'S_N{ch}_'+k]=v
            for port in ports[NCH*sl:NCH*sl+NCH]:
                for k in allaxi:
                    if k not in ('arid','awid','rid','bid'):
                        c[f'M_H{port}_'+k]=f'h_{k}[{port}]' if k in hbm else ''
                line(f"assign h_arid[{port}] = 6'd0;")
                line(f"assign h_awid[{port}] = 6'd0;")
            inst(f'f2_mem_s{sl}_wrapper',f'u_mem{sl}',c)
    # Required disabled DDR stub plus safe shell unused-interface implementations.
    iface=hdk/'common/shell_stable/design/interfaces'
    for inc in ('unused_ddr_template.inc','unused_cl_sda_template.inc','unused_flr_template.inc','unused_apppf_irq_template.inc'):
        line('`include "'+inc+'"')
        used.update(re.findall(r'\b\w+\b',(iface/inc).read_text()))
    ports_vh=(iface/'cl_ports.vh').read_text()
    outputs=re.findall(r'output\s+logic\s*(?:\[[^]]+\]\s*)?(\w+)',ports_vh)
    # Independent diagnostic bits cross from core to the shell's 250 MHz domain.
    # Register the combinational LED values at their source before synchronization.
    SW=NW+3
    decl('shell_status',SW)
    inst('xpm_cdc_array_single','u_status_cdc',
         dict(src_clk='core_clk',src_in='{n_err,leds}',dest_clk='clk_main_a0',dest_out='shell_status'),
         dict(WIDTH=SW,DEST_SYNC_FF=4,SRC_INPUT_REG=1,INIT_SYNC_FF=1,SIM_ASSERT_CHK=0))
    constants={'cl_sh_id0':"32'hf0011d0f",'cl_sh_id1':"32'h1d51fedd",'cl_sh_status0':"32'h4f545055",'cl_sh_status1':"32'h7e42a626",'cl_sh_status2':f"{{{32-NW}'d0,shell_status[{SW-1}:3]}}",'cl_sh_status_vled':"{12'd0,hbm_ready,shell_status[2:0]}"}
    for name in outputs:
        if name not in used: line('assign '+name+' = '+constants.get(name,"'0")+';')
    line('endmodule')
    return '\n'.join(s)+'\n'


if __name__=='__main__':
    main()
